import type { DB, Deal, Message, Post, PriceUnit, User } from "./types";

function ago(days: number, hours = 0) {
  return new Date(Date.now() - (days * 24 + hours) * 3600_000).toISOString();
}

function photo(id: string) {
  return `https://images.unsplash.com/${id}?auto=format&fit=crop&w=1200&q=80`;
}

function post(input: {
  id: string;
  user_id: string;
  kind: Post["kind"];
  title: string;
  description: string;
  category: string;
  price: number;
  price_unit?: PriceUnit;
  condition?: string | null;
  image: string;
  days: number;
  status?: Post["status"];
}): Post {
  return {
    id: input.id,
    user_id: input.user_id,
    kind: input.kind,
    title: input.title,
    description: input.description,
    category: input.category,
    price: input.price,
    price_unit: input.price_unit ?? "fixed",
    condition: input.condition ?? null,
    images: [photo(input.image)],
    status: input.status ?? "active",
    created_at: ago(input.days, input.days % 5),
  };
}

